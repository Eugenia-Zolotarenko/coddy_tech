package Counter;

class MathUtils {
    // TODO: Create a public constant PI with value 3.14159
    public static final double PI = 3.14159;

    // TODO: Create a public constant HALF with value 0.5
    public static final double HALF = 0.5;

    // TODO: Create a static method square(int n) that returns n squared
    public static int square(int n){
        return n*n;
    }

    // TODO: Create a static method cube(int n) that returns n cubed
    public static int cube(int n){
        return n*n*n;
    }

    // TODO: Create a static method circleArea(double radius) that returns PI * radius * radius
    public static double circleArea(double radius){
        return PI*radius*radius;
    }
}
